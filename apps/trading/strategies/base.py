"""
Base Trading Strategy

This is the abstract base class that all trading strategies must implement.
Strategies are completely exchange-agnostic - they receive standardized data
and return standardized signals.

PURE PYTHON - NO DJANGO IMPORTS
"""
import logging
from abc import ABC, abstractmethod
from typing import Dict, Any, Optional, List
from decimal import Decimal
from datetime import datetime

logger = logging.getLogger('trading.strategies')


class Signal:
    """
    Represents a trading signal generated by a strategy.
    """
    def __init__(
        self,
        action: str,
        symbol: str,
        amount: float,
        price: Optional[float] = None,
        order_type: str = 'market',
        stop_loss: Optional[float] = None,
        take_profit: Optional[float] = None,
        reason: str = '',
        metadata: Optional[Dict] = None
    ):
        """
        Initialize a trading signal.

        Args:
            action: 'buy', 'sell', 'close', or 'hold'
            symbol: Trading pair (e.g., 'BTC/USDT')
            amount: Order amount in base currency
            price: Limit price (None for market orders)
            order_type: 'market' or 'limit'
            stop_loss: Stop-loss price
            take_profit: Take-profit price
            reason: Human-readable reason for the signal
            metadata: Additional strategy-specific data
        """
        self.action = action.lower()
        self.symbol = symbol
        self.amount = float(amount)
        self.price = float(price) if price else None
        self.order_type = order_type.lower()
        self.stop_loss = float(stop_loss) if stop_loss else None
        self.take_profit = float(take_profit) if take_profit else None
        self.reason = reason
        self.metadata = metadata or {}
        self.timestamp = datetime.utcnow()

    def to_dict(self) -> Dict[str, Any]:
        """Convert signal to dictionary for adapter consumption."""
        return {
            'action': self.action,
            'symbol': self.symbol,
            'amount': self.amount,
            'price': self.price,
            'type': self.order_type,
            'stop_loss': self.stop_loss,
            'take_profit': self.take_profit,
            'reason': self.reason,
            'metadata': self.metadata,
            'timestamp': self.timestamp.isoformat(),
        }

    def __repr__(self) -> str:
        return f"Signal({self.action} {self.amount} {self.symbol} @ {self.price or 'market'})"


class BaseStrategy(ABC):
    """
    Abstract base class for all trading strategies.

    Strategies are PURE LOGIC - they:
    - Receive standardized market data (OHLCV, orderbook, etc.)
    - Receive standardized account info (balance, positions)
    - Return standardized signals (buy/sell/hold)

    They NEVER:
    - Import Django models
    - Call exchange APIs directly
    - Handle persistence
    """

    def __init__(self, parameters: Dict[str, Any] = None):
        """
        Initialize strategy with parameters.

        Args:
            parameters: Strategy-specific configuration
        """
        self.parameters = parameters or {}
        self.is_running = False
        self.last_signal: Optional[Signal] = None

        # Performance tracking
        self.signals_generated = 0
        self.signals_executed = 0

        # Validate parameters
        self._validate_parameters()

    @property
    @abstractmethod
    def name(self) -> str:
        """Return the strategy name."""
        pass

    @property
    def required_parameters(self) -> List[str]:
        """
        List of required parameter names.
        Override in subclass to define required parameters.
        """
        return []

    def _validate_parameters(self):
        """Validate that all required parameters are present."""
        missing = [p for p in self.required_parameters if p not in self.parameters]
        if missing:
            raise ValueError(f"Missing required parameters: {missing}")

    @abstractmethod
    def execute(
        self,
        market_data: Dict[str, Any],
        account_info: Dict[str, Any],
        current_position: Optional[Dict[str, Any]] = None
    ) -> Optional[Signal]:
        """
        Execute strategy logic and generate a signal.

        This is the main method that contains the trading algorithm.
        It should be stateless - all necessary state should be derived
        from the input parameters.

        Args:
            market_data: Dict containing:
                - ticker: {last, bid, ask, high, low, volume}
                - ohlcv: List of {timestamp, open, high, low, close, volume}
                - orderbook: {bids, asks} (optional)
            account_info: Dict containing:
                - balance: {total: {}, free: {}, used: {}}
                - exchange: exchange name
            current_position: Dict containing current position info (if any):
                - symbol, side, contracts, entry_price, unrealized_pnl

        Returns:
            Signal object if action should be taken, None if hold
        """
        pass

    def should_enter_long(
        self,
        market_data: Dict[str, Any],
        account_info: Dict[str, Any]
    ) -> bool:
        """
        Determine if conditions are met to enter a long position.
        Override in subclass with specific logic.
        """
        return False

    def should_enter_short(
        self,
        market_data: Dict[str, Any],
        account_info: Dict[str, Any]
    ) -> bool:
        """
        Determine if conditions are met to enter a short position.
        Override in subclass with specific logic.
        """
        return False

    def should_exit_long(
        self,
        market_data: Dict[str, Any],
        current_position: Dict[str, Any]
    ) -> bool:
        """
        Determine if conditions are met to exit a long position.
        Override in subclass with specific logic.
        """
        return False

    def should_exit_short(
        self,
        market_data: Dict[str, Any],
        current_position: Dict[str, Any]
    ) -> bool:
        """
        Determine if conditions are met to exit a short position.
        Override in subclass with specific logic.
        """
        return False

    def calculate_position_size(
        self,
        account_info: Dict[str, Any],
        current_price: float,
        symbol: str
    ) -> float:
        """
        Calculate position size based on risk management rules.

        Default implementation uses percentage of available balance.
        Override for custom position sizing.

        Args:
            account_info: Account balance information
            current_price: Current market price
            symbol: Trading symbol

        Returns:
            Position size in base currency
        """
        # Default: use 10% of free balance
        risk_percentage = self.parameters.get('risk_percentage', 10) / 100
        quote_currency = symbol.split('/')[1] if '/' in symbol else 'USDT'

        free_balance = account_info.get('balance', {}).get('free', {}).get(quote_currency, 0)
        position_value = float(free_balance) * risk_percentage

        if current_price > 0:
            return position_value / current_price
        return 0

    def calculate_stop_loss(
        self,
        entry_price: float,
        side: str,
        atr: Optional[float] = None
    ) -> Optional[float]:
        """
        Calculate stop-loss price.

        Args:
            entry_price: Entry price
            side: 'long' or 'short'
            atr: Average True Range (optional, for ATR-based stops)

        Returns:
            Stop-loss price or None if not using stop-loss
        """
        stop_loss_pct = self.parameters.get('stop_loss_percentage', 2) / 100

        if side.lower() == 'long':
            return entry_price * (1 - stop_loss_pct)
        else:
            return entry_price * (1 + stop_loss_pct)

    def calculate_take_profit(
        self,
        entry_price: float,
        side: str
    ) -> Optional[float]:
        """
        Calculate take-profit price.

        Args:
            entry_price: Entry price
            side: 'long' or 'short'

        Returns:
            Take-profit price or None if not using take-profit
        """
        take_profit_pct = self.parameters.get('take_profit_percentage', 5) / 100

        if side.lower() == 'long':
            return entry_price * (1 + take_profit_pct)
        else:
            return entry_price * (1 - take_profit_pct)

    def get_status(self) -> Dict[str, Any]:
        """Get current strategy status."""
        return {
            'name': self.name,
            'is_running': self.is_running,
            'signals_generated': self.signals_generated,
            'signals_executed': self.signals_executed,
            'last_signal': self.last_signal.to_dict() if self.last_signal else None,
            'parameters': self.parameters,
        }

    def update_parameters(self, new_parameters: Dict[str, Any]):
        """Update strategy parameters."""
        self.parameters.update(new_parameters)
        self._validate_parameters()

    def __str__(self) -> str:
        return f"{self.name}(running={self.is_running})"

    def __repr__(self) -> str:
        return f"{self.__class__.__name__}(parameters={self.parameters})"
